"""Есть ли вокруг праздников чистый прирост за 30 дней, или только сдвиг спроса.

Целевое окно 14.02-15.03.2026 = дни 409..438; 23.02 это день 418 (10-й день окна), 08.03 -
день 431 (23-й). Прошлогодний аналог окна - дни 44..73, праздники в днях 53 и 66.

RMSLE считается на МЕСЯЧНОЙ СУММЕ, поэтому перераспределение спроса внутри окна не значит
ничего - важен только чистый прирост итога. Плюс однородная часть прироста уже съедена
калибровкой уровня (EL = 2,3284 подогнан на LB), так что полезна лишь клиентская
неоднородность.

База для каждого дня - тот же день недели на +-7,14,21,28 днях, с выбросом самих праздничных
дней. Это снимает и день недели, и медленный тренд.
"""
import sys; sys.path.insert(0, "code")
import numpy as np
from datetime import timedelta
from common import panel, D0, N_DAYS

G = panel("gmv").astype(np.float32)
tot = G.sum(0)                       # суммарный GMV по дням
act = (G > 0).mean(0)                # доля активных клиентов по дням
HOL = {53: "23.02.2025", 66: "08.03.2025", 0: "01.01.2025", 6: "07.01.2025",
       120: "01.05.2025", 128: "09.05.2025", 307: "04.11.2025", 364: "31.12.2025"}
hol_win = set()
for h in HOL:
    for k in range(-3, 4):
        hol_win.add(h + k)
for k in range(355, 375):            # новогодние каникулы целиком
    hol_win.add(k)

def base_of(series, d):
    vals = [series[d + k] for k in (-28, -21, -14, -7, 7, 14, 21, 28)
            if 0 <= d + k < N_DAYS and (d + k) not in hol_win]
    return float(np.mean(vals)) if len(vals) >= 3 else np.nan

print("ФОРМА ВОКРУГ ПРОШЛОГОДНЕГО ОКНА (дни 44..73 = 14.02-15.03.2025)")
print(f"{'день':>5} {'дата':>12} {'GMV/база':>9} {'актив/база':>11} {'':>3}")
for d in range(44, 74):
    dt = D0 + timedelta(days=d)
    bg, ba = base_of(tot, d), base_of(act, d)
    mark = "  <<< 23.02" if d == 53 else ("  <<< 08.03" if d == 66 else "")
    print(f"{d:5d} {str(dt):>12} {tot[d]/bg:9.4f} {act[d]/ba:11.4f}{mark}")

print("\nЧИСТЫЙ ПРИРОСТ ЗА ОКНО (сумма факта / сумма базы)")
for name, lo, hi in (("прошлогоднее целевое 44..73", 44, 74),
                     ("нейтральное 100..129", 100, 130),
                     ("нейтральное 200..229", 200, 230),
                     ("нейтральное 250..279", 250, 280),
                     ("новогоднее 349..378", 349, 379)):
    b = np.array([base_of(tot, d) for d in range(lo, hi)])
    a = tot[lo:hi]
    m = np.isfinite(b)
    print(f"  {name:<28} {a[m].sum()/b[m].sum():.4f}")

print("\nРАЗЛОЖЕНИЕ: однородная часть против клиентской")
W  = G[:, 44:74].sum(1)                                  # прошлогоднее целевое окно
for nm, lo in (("100..129", 100), ("200..229", 200), ("250..279", 250)):
    Nw = G[:, lo:lo+30].sum(1)
    lw, ln = np.log1p(W), np.log1p(Nw)
    both = (W > 0) & (Nw > 0)
    print(f"  против {nm}: сдвиг средней log1p {lw.mean()-ln.mean():+.4f}, "
          f"доля активных {(W>0).mean():.4f} против {(Nw>0).mean():.4f}, "
          f"corr(log1p) {np.corrcoef(lw, ln)[0,1]:.4f}, "
          f"sd разности на активных {(lw[both]-ln[both]).std():.4f}")
print("\ndone")
