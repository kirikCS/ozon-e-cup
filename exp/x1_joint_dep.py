"""Есть ли зависимость между днями СВЕРХ общего множителя клиента?

Наш считыватель — и квадратура Фруллани, и симуляция путей — предполагает, что при данной frailty
дни горизонта условно НЕЗАВИСИМЫ. Преобразование Лапласа факторизуется по дням именно поэтому.

Если предположение верно, то вся зависимость между днями объясняется одним общим множителем на
клиента, и она ОБМЕННАЯ: корреляция любой пары дней одинакова и от расстояния между днями не
зависит. Если же есть короткодействующая структура — покупка вчера меняет вероятность покупки
сегодня сверх собственного темпа клиента, — корреляция будет убывать с лагом.

Это решает судьбу сразу трёх тяжёлых семейств: траекторных трансформеров, нормализующих потоков и
SDE. Их единственное преимущество перед нашим считывателем — моделирование СОВМЕСТНОГО
распределения горизонта вместо поденных маргиналей. Если совместной структуры нет, преимущество
пустое, и трогать их незачем.

Проверка. Базовая линия независимости — мультипликативная: P(покупка у клиента i в день d)
приблизительно r_i * m_d / mbar, где r_i — доля активных дней клиента, m_d — доля активных
клиентов в день d. Она убирает и разный темп клиентов, и разный календарь дней. Остаток
R = Z - E не должен иметь автокорреляции ни на каком лаге.

Контроль обязателен: те же дни, переставленные ВНУТРИ клиента. Перестановка сохраняет и r_i, и
общий множитель, но разрушает порядок. Если статистика на контроле не обнуляется, значит она
меряет не то, что я думаю, и выводы делать нельзя.

Меряется отдельно две вещи, потому что они входят в считыватель по-разному:
  ФАКТ покупки  — влияет на p_d в hurdle;
  ВЕЛИЧИНА чека — влияет на m_d, и её зависимость проверяется только по дням с покупкой.
"""
import sys
sys.path.insert(0, "code")
import numpy as np
from common import panel, NU

D0_, D1 = 60, 409          # первые дни отбрасываем: там доля активных ещё не установилась
LAGS = list(range(1, 15)) + [21, 28, 30]
G = panel("gmv")[:, D0_:D1]
Z = (G > 0).astype(np.float32)
T = Z.shape[1]
print(f"панель {Z.shape}, доля активных дней {Z.mean():.4f}", flush=True)

def lag_profile(R, lags):
    """корреляция остатка с самим собой на лаге k, по всем клиентам и дням сразу"""
    sd = R.std()
    out = []
    for k in lags:
        a, b = R[:, :-k], R[:, k:]
        out.append(float((a * b).mean() / (sd * sd)))
    return out

def residual(Z):
    r = Z.mean(1, keepdims=True)                 # темп клиента
    m = Z.mean(0, keepdims=True)                 # календарь дня
    E = r * m / Z.mean()
    return (Z - E).astype(np.float32)

R = residual(Z)
prof = lag_profile(R, LAGS)

rng = np.random.default_rng(0)
Zs = Z.copy()
idx = np.argsort(rng.random(Zs.shape), axis=1)   # своя перестановка дней у каждого клиента
Zs = np.take_along_axis(Zs, idx, axis=1)
Rs = residual(Zs)
profs = lag_profile(Rs, LAGS)

print(f"\n{'лаг':>5} {'факт покупки':>14} {'контроль (перемешано)':>22} {'сверх контроля':>16}")
for k, a, b in zip(LAGS, prof, profs):
    print(f"{k:>5} {a:14.5f} {b:22.5f} {a-b:16.5f}")

pos = Z > 0
LG = np.where(pos, np.log1p(G), 0.0).astype(np.float32)
cm = LG.sum(1) / np.maximum(pos.sum(1), 1)
A = np.where(pos, LG - cm[:, None], 0.0).astype(np.float32)
dm = A.sum(0) / np.maximum(pos.sum(0), 1)
A = np.where(pos, A - dm[None, :], 0.0).astype(np.float32)
print(f"\n{'лаг':>5} {'величина чека':>15} {'пар дней':>12}")
for k in LAGS[:8]:
    p, q = A[:, :-k], A[:, k:]
    both = (pos[:, :-k] & pos[:, k:])
    n = int(both.sum())
    if n < 1000:
        continue
    num = float((p * q * both).sum() / n)
    v1 = float((p * p * both).sum() / n)
    v2 = float((q * q * both).sum() / n)
    print(f"{k:>5} {num/np.sqrt(v1*v2):15.5f} {n:12d}")

print("""
Как читать. Плоский профиль по лагу = вся зависимость обменная, её объясняет общий множитель
клиента, и наш факторизованный считыватель верен. Убывание с лагом = есть короткодействующая
структура, которой считыватель не видит, и тогда совместное моделирование горизонта имеет смысл.
Контроль обязан быть около нуля на всех лагах.""")
print("\ndone")
