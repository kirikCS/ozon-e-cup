"""Однородна ли праздничная надбавка или клиентски неоднородна — против ЛОКАЛЬНЫХ соседей.

В p1 сравнение шло с далёкими окнами, а доля активных на платформе растёт с 0,403 до 0,500 за
год, и рост забивал эффект. Здесь окно 44..73 сравнивается с соседними слева (14..43) и справа
(74..103) — те же клиенты, тот же уровень зрелости платформы, разница только в празднике.

Если надбавка однородна, она вся уйдёт в калибровку уровня (EL = 2,3284 подогнан на LB) и
пользы не даст. Полезна только клиентская часть — и её мы, возможно, уже сняли прошлогодним
зондом (theta = +0,02149, S/N 10,2), который брал ровно это окно как контраст к фону.
"""
import sys; sys.path.insert(0, "code")
import numpy as np
from common import panel

G = panel("gmv").astype(np.float32)
W  = G[:, 44:74].sum(1)                    # праздничное окно 14.02-15.03.2025
L  = G[:, 14:44].sum(1)                    # слева, 15.01-13.02
R  = G[:, 74:104].sum(1)                   # справа, 16.03-14.04
NB = 0.5 * (L + R)

lw, lnb = np.log1p(W), np.log1p(NB)
print(f"доля активных: окно {(W>0).mean():.4f}, слева {(L>0).mean():.4f}, справа {(R>0).mean():.4f}")
print(f"суммарный GMV: окно/фон = {W.sum()/NB.sum():.4f}")
print(f"сдвиг средней log1p: {lw.mean()-lnb.mean():+.5f}")

both = (W > 0) & (NB > 0)
d = lw[both] - lnb[both]
print(f"\nна активных в обоих ({both.mean():.4f} клиентов):")
print(f"  средняя разность {d.mean():+.5f}   sd {d.std():.5f}")
print(f"  ОДНОРОДНАЯ часть = средняя = {d.mean():+.5f}")
print(f"  отношение неоднородности sd/|среднее| = {d.std()/abs(d.mean()):.1f}")

# сколько неоднородности ОБЪЯСНИМО, а не шум: устойчива ли она между половинами окна
A = np.log1p(G[:, 44:59].sum(1)); B = np.log1p(G[:, 59:74].sum(1))
An = np.log1p(0.5*(G[:, 14:29].sum(1) + G[:, 74:89].sum(1)))
Bn = np.log1p(0.5*(G[:, 29:44].sum(1) + G[:, 89:104].sum(1)))
m2 = (G[:, 44:59].sum(1) > 0) & (G[:, 59:74].sum(1) > 0) & (An > 0) & (Bn > 0)
r = np.corrcoef((A-An)[m2], (B-Bn)[m2])[0, 1]
print(f"\nустойчивость надбавки между половинами окна: corr = {r:+.4f}")
print(f"  (нулевая = вся неоднородность шум; заметная = есть клиентский эффект)")
print(f"  доля объяснимой дисперсии надбавки ~ {max(r,0):.4f}")

# насколько это уже в прошлогоднем зонде: он брал контраст окна к фону, то есть ровно d
print(f"\nпрошлогодний зонд брал контраст окна к фону — это и есть измеренная здесь величина.")
print("\ndone")
