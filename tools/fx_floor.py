"""Правильный шумовой потолок public->private и пересчёт всех кандидатов.

ИСПРАВЛЕНИЕ. Я масштабировал потолок по числу подгоняемых параметров как sqrt(d).
Верно ЛИНЕЙНО: классический оптимизм d-параметрической подгонки равен d*sigma^2/n
в единицах m^2, то есть d*sigma^2/(2*m*n) в единицах RMSLE.

Проверка формулы на нулевом тесте (code/fx_nulltest.py, d=20, n=50000, m=1.6697,
sigma^2 = m^2 = 2.788):
    формула: 20*2.788/(2*1.6697*50000) = 3.34e-4
    замер на насыщении (D=0.050): 3.60e-4     -> сходится в пределах 8%
Зависимость от радиуса (доля насыщения), снята там же:
    D=0.005 -> 0.28   D=0.010 -> 0.50   D=0.020 -> 0.86
    D=0.027 -> 0.94   D=0.035 -> 0.95   D=0.050 -> 1.00

Следствие, которое всё меняет: у ОДНОГО параметра потолок 1.65e-5, а не 7e-5.
Малопараметрические конструкции гораздо безопаснее, чем я сказал.

Usage: python -u code/fx_floor.py > model_out/floor.log 2>&1
"""
import numpy as np

N_PUB, M_REF, REC = 50_000, 1.6465, 1.646487285085104
SIG2 = M_REF**2
SAT_D = np.array([0.005, 0.010, 0.020, 0.027, 0.035, 0.050, 0.200])
SAT_F = np.array([0.28, 0.50, 0.86, 0.94, 0.95, 1.00, 1.00])


def floor(d, radius):
    """Шумовой потолок публичного выигрыша при d подгоняемых параметрах."""
    sat = float(np.interp(radius, SAT_D, SAT_F))
    return d * SIG2 / (2 * M_REF * N_PUB) * sat


print("=" * 92)
print("ШУМОВОЙ ПОТОЛОК: d * sigma^2 / (2 m n) * доля_насыщения(радиус)")
print("=" * 92)
print(f"на один параметр при насыщении: {floor(1, 0.2):.7f}")
print(f"{'d':>5} " + " ".join(f"{r:>9.3f}" for r in [0.005, 0.010, 0.020, 0.027, 0.035, 0.050]))
for d in [1, 2, 5, 20, 26, 29]:
    print(f"{d:5d} " + " ".join(f"{floor(d,r):9.6f}"
                                for r in [0.005, 0.010, 0.020, 0.027, 0.035, 0.050]))

CAND = [
    # имя, d (подгоняемых параметров), радиус ||z||_C, публичный выигрыш
    ("SAFE_beat_record",      26, 0.0274, 0.000229),
    ("B26_opt",               26, 0.0306, 0.000251),
    ("B26_tight_D010",        26, 0.0093, 0.000122),
    ("оптимум базиса 29",     29, 0.0348, 0.000379),
    ("PAIR_best (2 вектора)",  1, 0.0080, 0.000038),
]
print()
print("=" * 92)
print("ПЕРЕСЧЁТ ВСЕХ КАНДИДАТОВ")
print("=" * 92)
print(f"{'кандидат':>24} {'d':>4} {'радиус':>8} {'public':>10} {'потолок':>10} "
      f"{'S/N':>6} {'ожид. private':>14} {'вердикт':>11}")
for nm, d, r, g in CAND:
    fl = floor(d, r)
    sn = g / fl
    exp_priv = g - fl
    v = "НАСТОЯЩИЙ" if sn > 2 else "спорный" if sn > 1 else "подгонка"
    print(f"{nm:>24} {d:4d} {r:8.4f} {g:+10.6f} {fl:10.6f} {sn:6.2f} "
          f"{exp_priv:+14.6f} {v:>11}")

print()
print("=" * 92)
print("ЗОНД КРИВИЗНЫ: тот же расчёт для одного параметра")
print("=" * 92)
f1 = floor(1, 0.2)
print(f"потолок одного параметра: {f1:.7f}   порог доверия S/N=2: {2*f1:.7f}")
print(f"{'замер зонда':>14} {'Cov(y,v)':>10} {'потенциал':>11} {'S/N':>7} {'вердикт':>11}")
A = 0.020
for mp in [1.6459, 1.6461, 1.6463, 1.6465, 1.6466088, 1.6468, 1.6470, 1.6473]:
    cov = (A**2 - (mp**2 - REC**2)) / (2 * A)
    gain = cov**2 / (2 * REC)
    sn = gain / f1
    v = "НАСТОЯЩИЙ" if sn > 2 else "спорный" if sn > 1 else "пусто"
    print(f"{mp:14.7f} {cov:+10.5f} {gain:+11.6f} {sn:7.2f} {v:>11}")
print()
print(f"Зонд окупается, если |Cov(y,v)| > {np.sqrt(2*f1*2*REC):.4f}, то есть если")
print(f"замер выйдет за пределы {REC + A**2/(2*REC) - np.sqrt(2*f1*2*REC)*2*A/(2*REC):.5f}"
      f" .. {REC + A**2/(2*REC) + np.sqrt(2*f1*2*REC)*2*A/(2*REC):.5f} — почти любой исход.")
